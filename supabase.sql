-- Run this once in Supabase Dashboard > SQL Editor.
-- The app connects from its trusted server/Worker using a server-side secret key.

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null
);

create table if not exists public.app_items (
  id text primary key,
  payload jsonb not null check (jsonb_typeof(payload) = 'object')
);

create table if not exists public.app_history (
  id text primary key,
  payload jsonb not null check (jsonb_typeof(payload) = 'object')
);

create table if not exists public.app_deleted_ids (
  id text primary key
);

create table if not exists public.app_login_attempts (
  id bigint generated by default as identity primary key,
  ip text not null,
  created_at bigint not null
);

create index if not exists app_login_attempts_ip_time
  on public.app_login_attempts (ip, created_at);

alter table public.app_settings enable row level security;
alter table public.app_items enable row level security;
alter table public.app_history enable row level security;
alter table public.app_deleted_ids enable row level security;
alter table public.app_login_attempts enable row level security;

revoke all on table public.app_settings, public.app_items, public.app_history,
  public.app_deleted_ids, public.app_login_attempts from anon, authenticated;
grant all on table public.app_settings, public.app_items, public.app_history,
  public.app_deleted_ids, public.app_login_attempts to service_role;
grant usage, select on sequence public.app_login_attempts_id_seq to service_role;
